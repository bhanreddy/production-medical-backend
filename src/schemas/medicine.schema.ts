import { z } from 'zod';

const baseMedicineSchema = z.object({
  name: z.string().min(1).max(300),
  product_type: z.enum([
    'MEDICINE',
    'OTC',
    'SURGICAL',
    'MEDICAL_DEVICE',
    'FMCG',
    'WELLNESS',
    'COSMETIC',
    'PERSONAL_CARE',
    'CONSUMABLE',
    'OTHER',
  ]).default('MEDICINE'),
  brand_name: z.string().optional().nullable(),
  generic_name: z.string().optional().nullable(),
  composition: z.string().optional().nullable(),
  dosage_form: z.string().optional().nullable(),
  strength: z.string().optional().nullable(),
  pack_size: z.string().optional().nullable(),
  base_unit: z.string().default('strip'),
  sale_unit: z.string().default('strip'),
  conversion_factor: z.number().positive().default(1.0),
  manufacturer: z.string().optional().nullable(),
  marketer: z.string().optional().nullable(),
  category: z.string().default('tablet'),
  category_id: z.string().optional().nullable(),
  subcategory_id: z.string().optional().nullable(),
  hsn_code: z.string().optional().nullable(),
  gst_rate: z.number().refine(v => [0, 5, 12, 18, 28].includes(v)).default(12),
  unit: z.string().default('strip'),
  is_schedule_h1: z.boolean().default(false),
  prescription_required: z.boolean().default(false),
  schedule_classification: z.enum([
    'NONE',
    'SCHEDULE_H',
    'SCHEDULE_H1',
    'SCHEDULE_X',
    'NARCOTIC',
  ]).default('NONE'),
  cold_chain_required: z.boolean().default(false),
  storage_instructions: z.string().optional().nullable(),
  minimum_margin_percent: z.number().min(0).default(0),
  preferred_supplier_id: z.string().optional().nullable(),
  low_stock_threshold: z.number().int().positive().default(10),
  primary_barcode: z.string().optional().nullable(),
  barcode: z.string().optional().nullable(),
  store_id: z.string().optional().nullable(),
  organization_id: z.string().optional().nullable(),
  clinic_id: z.string().optional(),
  _local_id: z.string().optional(),
});

export const createMedicineSchema = baseMedicineSchema.transform(({ clinic_id, ...rest }) => rest);
export const updateMedicineSchema = baseMedicineSchema.partial().transform(({ clinic_id, ...rest }) => rest);
