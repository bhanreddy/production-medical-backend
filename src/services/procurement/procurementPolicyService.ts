// procurementPolicyService.ts — Organization Procurement Policies & Approval Matrix
import { localDb } from '../../local-db';
import { localMutate } from '../../lib/localMutate';
import { ProcurementPolicy, ProcurementMode } from '../../domain/procurementTypes';
import { v4 as uuidv4 } from 'uuid';

export class ProcurementPolicyService {
  /**
   * Fetch policy for an organization or return sensible enterprise defaults
   */
  static getPolicy(organizationId: string): ProcurementPolicy {
    const row: any = localDb
      .prepare(`SELECT * FROM procurement_policies WHERE (organization_id = ?) AND _deleted = 0 LIMIT 1`)
      .get(organizationId);

    if (row) {
      return {
        id: row.id,
        organizationId: row.organization_id,
        procurementMode: (row.procurement_mode || 'ENTERPRISE') as ProcurementMode,
        storeManagerApprovalLimitPaise: Number(row.store_manager_approval_limit_paise ?? 1000000), // ₹10,000
        regionalManagerApprovalLimitPaise: Number(row.regional_manager_approval_limit_paise ?? 10000000), // ₹1,00,000
        enforceMakerChecker: Boolean(row.enforce_maker_checker),
        priceVarianceTolerancePct: Number(row.price_variance_tolerance_pct ?? 0.50),
        quantityVarianceTolerancePct: Number(row.quantity_variance_tolerance_pct ?? 2.00),
        taxVarianceExact: Boolean(row.tax_variance_exact ?? 1),
        minShelfLifeDaysReceipt: Number(row.min_shelf_life_days_receipt ?? 180),
        allowExcessReceiptTolerancePct: Number(row.allow_excess_receipt_tolerance_pct ?? 2.00),
        autoGenerateDebitNote: Boolean(row.auto_generate_debit_note ?? 1),
        paymentTermsDefault: row.payment_terms_default || 'NET_30',
      };
    }

    return {
      organizationId,
      procurementMode: 'ENTERPRISE',
      storeManagerApprovalLimitPaise: 1000000,
      regionalManagerApprovalLimitPaise: 10000000,
      enforceMakerChecker: false,
      priceVarianceTolerancePct: 0.50,
      quantityVarianceTolerancePct: 2.00,
      taxVarianceExact: true,
      minShelfLifeDaysReceipt: 180,
      allowExcessReceiptTolerancePct: 2.00,
      autoGenerateDebitNote: true,
      paymentTermsDefault: 'NET_30',
    };
  }

  /**
   * Save or update policy for an organization
   */
  static setPolicy(policy: Partial<ProcurementPolicy> & { organizationId: string }): ProcurementPolicy {
    const existing = this.getPolicy(policy.organizationId);
    const id = existing.id || uuidv4();

    localMutate({
      table: 'procurement_policies',
      operation: existing.id ? 'UPDATE' : 'INSERT',
      data: {
        id,
        _local_id: id,
        organization_id: policy.organizationId,
        procurement_mode: policy.procurementMode || existing.procurementMode,
        store_manager_approval_limit_paise: policy.storeManagerApprovalLimitPaise ?? existing.storeManagerApprovalLimitPaise,
        regional_manager_approval_limit_paise: policy.regionalManagerApprovalLimitPaise ?? existing.regionalManagerApprovalLimitPaise,
        enforce_maker_checker: policy.enforceMakerChecker ? 1 : 0,
        price_variance_tolerance_pct: policy.priceVarianceTolerancePct ?? existing.priceVarianceTolerancePct,
        quantity_variance_tolerance_pct: policy.quantityVarianceTolerancePct ?? existing.quantityVarianceTolerancePct,
        tax_variance_exact: policy.taxVarianceExact !== undefined ? (policy.taxVarianceExact ? 1 : 0) : 1,
        min_shelf_life_days_receipt: policy.minShelfLifeDaysReceipt ?? existing.minShelfLifeDaysReceipt,
        allow_excess_receipt_tolerance_pct: policy.allowExcessReceiptTolerancePct ?? existing.allowExcessReceiptTolerancePct,
        auto_generate_debit_note: policy.autoGenerateDebitNote !== undefined ? (policy.autoGenerateDebitNote ? 1 : 0) : 1,
        payment_terms_default: policy.paymentTermsDefault || existing.paymentTermsDefault,
      },
    });

    return this.getPolicy(policy.organizationId);
  }

  /**
   * Evaluates required approval level based on amount
   */
  static getRequiredApprovalRole(organizationId: string, amountPaise: number): 'STORE_MANAGER' | 'REGIONAL_MANAGER' | 'HQ_PROCUREMENT' {
    const policy = this.getPolicy(organizationId);
    if (amountPaise <= policy.storeManagerApprovalLimitPaise) {
      return 'STORE_MANAGER';
    }
    if (amountPaise <= policy.regionalManagerApprovalLimitPaise) {
      return 'REGIONAL_MANAGER';
    }
    return 'HQ_PROCUREMENT';
  }
}
